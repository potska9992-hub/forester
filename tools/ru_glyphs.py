# Cyrillic 5x7 glyphs in the style of the Adafruit GFX classic font (8 rows, row 7 = descender).
# '#' = pixel on. Capitals use rows 0-6, lowercase rows 2-6 (tall letters 0-6, descenders to row 7).
G = {}
def g(ch, rows):
    rows = [r.ljust(5, '.') for r in rows]
    rows += ['.....'] * (8 - len(rows))
    assert len(rows) == 8 and all(len(r) == 5 for r in rows), ch
    G[ch] = rows
def low(ch, rows, top=2):   # rows placed starting at row `top`
    g(ch, ['.....'] * top + rows)

